def all_lessons():
    return [dict(lesson, codes=list(lesson['codes']), topic=_TOPIC[lesson['id']], number=index + 1)
            for index, lesson in enumerate(LESSONS)]

def by_id(identifier):
    return next((lesson for lesson in all_lessons() if lesson["id"] == identifier), None)


def next_lesson(identifier):
    lessons = all_lessons()
    index = next((i for i, lesson in enumerate(lessons) if lesson['id'] == identifier), -1)
    return lessons[index + 1] if 0 <= index < len(lessons) - 1 else None


def lessons_for_code(code):
    """Every lesson that teaches this sign, in course order."""
    return [lesson for lesson in all_lessons() if code in lesson['codes']]


def topic_label(identifier):
    return next((topic for topic in TOPICS if topic['id'] == identifier), None)
